// Every K but segment 0's is floor(2^39 / (65536 + 256 i) / 16) * 16, the start of segment i in 1/8ths. The table
// was fit to probe data; segments it left loose (39, 161, 162, 253, 255) use that formula, which games confirmed
// for 39 and 161, and large-w UV planes (gpu/probe exp136, exp138) for 105 and 106.
int64_t GESetupRecip(uint64_t absDet, int *e) {
	const uint32_t hi = (uint32_t)(absDet >> 32);
	const int ex = hi ? 63 - (int)clz32_nonzero(hi) : 31 - (int)clz32_nonzero((uint32_t)absDet);
	*e = ex;
	const int index = (int)((absDet << 16) >> ex) - 65536;
	const GESetupRecipSegment &seg = geSetupRecip[index >> 8];
	return (2 * (int64_t)seg.k + seg.m * (index & 255)) >> 8;
}

float GELightPow(float v, float e) {
	if (e <= 0.0f) {
		return 1.0f;
	}
	if (v > 0.0f) {
		// PSPLightPow, but the product is exact, and keeps 19 fraction bits of the log (units of 16 in
		// the float's bits), truncated toward zero (gpu/probe exp102: e = 1.1 and 0.3, exp4: e = 0.05).
		int32_t ix;
		memcpy(&ix, &v, sizeof(ix));
		double t = std::trunc((double)e * (double)(ix - 0x3F800000) * (1.0 / 16.0)) * 16.0 + 1065353216.0;
		t = t >= 0.0 ? (t < 2139095039.0 ? t : 2139095039.0) : 0.0;
		int32_t iy = (int32_t)t;
		float y;
		memcpy(&y, &iy, sizeof(y));
		return y;
	}
	// Negative stays negative, so let's just return the original.
	return v;
}

int GELineCoverageAlpha(int64_t x0, int64_t y0, int64_t x1, int64_t y1, int px, int py) {
	int64_t PX = (int64_t)px * 16 + 16 / 2;
	int64_t PY = (int64_t)py * 16 + 16 / 2;
	// A diagonal line is y-major (gpu/probe exp137).
	if (std::abs(x1 - x0) <= std::abs(y1 - y0)) {
		std::swap(x0, y0);
		std::swap(x1, y1);
		std::swap(PX, PY);
	}
	const int64_t den = x1 - x0;
	if (den == 0)
		return 128;
	// The minor offset at the pixel walks from v0 along the major axis with a slope like a triangle plane's
	// gradient: the setup reciprocal of the major length, 14 fraction bits per subpixel, floored
	// (gpu/probe exp112, exact).
	int e;
	const int64_t q = GESetupRecip((uint64_t)std::abs(den), &e);
	const int64_t walk = den > 0 ? PX - x0 : x0 - PX;
	const int64_t slope = (-16 * (y1 - y0) * q) >> (e + 2);
	const int64_t o = ((16 * (PY - y0)) * (1 << 14) + slope * walk) >> 14;
	return (int)std::clamp<int64_t>(128 - (o < 0 ? -o : o), 0, 255);
}
